#!/usr/bin/env python3
"""Bundle authored specialty report models for offline native OS reporting."""
import json
from pathlib import Path
root=Path(__file__).resolve().parent.parent
shell=(root/'templates/native-specialty.html').read_text().replace('__RUNTIME__',(root/'templates/native-specialty-runtime.js').read_text())
models=json.loads((root/'tg-specialty-models.json').read_text())
header='/* Generated by scripts/build-specialty-models.py. Source models are authored checklists. */\n(function(){\n "use strict";\n const MODEL_DATA='+json.dumps(models,ensure_ascii=False,separators=(',',':'))+';\n const SHELL='+json.dumps(shell,ensure_ascii=False)+';\n'
(root/'tg-specialty-templates.js').write_text(header+(root/'templates/native-specialty-host.js').read_text()+'\n})();\n')
