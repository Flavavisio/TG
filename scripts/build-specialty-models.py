#!/usr/bin/env python3
"""Bundle authored specialty report models for offline native OS reporting."""
import json
from pathlib import Path
root=Path(__file__).resolve().parent.parent
rules=(root/'templates/electrical-rules.js').read_text()
scie_rules=(root/'templates/scie-rules.js').read_text()
runtime=(root/'templates/native-specialty-runtime.js').read_text()
shell=(root/'templates/native-specialty.html').read_text().replace('__RUNTIME__',rules+'\n'+runtime)
scie_shell=(root/'templates/scie-term.html').read_text().replace('__RUNTIME__',scie_rules+'\n'+runtime)
models=json.loads((root/'tg-specialty-models.json').read_text())
header='/* Generated by scripts/build-specialty-models.py. Source models are authored checklists. */\n(function(){\n "use strict";\n const MODEL_DATA='+json.dumps(models,ensure_ascii=False,separators=(',',':'))+';\n const SHELL='+json.dumps(shell,ensure_ascii=False)+';\n const SCIE_SHELL='+json.dumps(scie_shell,ensure_ascii=False)+';\n'
(root/'tg-specialty-templates.js').write_text(header+rules+'\n'+scie_rules+'\n'+(root/'templates/native-specialty-host.js').read_text()+'\n})();\n')
mapping=json.loads((root/'templates/dgeg/relatorio-exploracao-map.json').read_text())
(root/'tg-electrical-legal.js').write_text('/* Generated by scripts/build-specialty-models.py. */\n'+(root/'templates/electrical-pdf.js').read_text().replace('__ELECTRICAL_MAP__',json.dumps(mapping,ensure_ascii=False,separators=(',',':'))))
