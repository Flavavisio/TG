// Audit actual entry pages and specialty templates without connecting to production.
const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const { chromium } = require('playwright');
const source = fs.readFileSync('app-principal.js', 'utf8');
const start = source.indexOf('        const REPORT_TEMPLATES_B64 = ');
const end = source.indexOf('\n        };', start) + 11;
const templates = {};
vm.runInNewContext(source.slice(start, end) + ';this.reports=REPORT_TEMPLATES_B64', templates);
const pages = fs.readdirSync('.').filter(name => name.endsWith('.html'));
const controls = 'input:not([type=checkbox]):not([type=radio]):not([type=range]):not([type=color]):not([type=hidden]):not([type=button]):not([type=submit]):not([type=reset]):not([type=image]):not([type=file]),textarea,select,[contenteditable="true"],[contenteditable="plaintext-only"],[contenteditable=""]';
const stripAppScripts = html => html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,
  tag => /src="tg-form-focus.js\?/.test(tag) ? tag : '');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_BINARY, headless: true, args: ['--no-sandbox'] });
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
    await context.route('**/*', route => {
      const url = new URL(route.request().url()), file = decodeURIComponent(url.pathname.slice(1));
      if (url.origin !== 'https://tg.test' || !fs.existsSync(file) || !fs.statSync(file).isFile()) return route.fulfill({ status: 404, body: '' });
      return route.fulfill({ contentType: file.endsWith('.html') ? 'text/html' : file.endsWith('.css') ? 'text/css' : 'text/javascript',
        body: file.endsWith('.html') ? stripAppScripts(fs.readFileSync(file, 'utf8')) : fs.readFileSync(file) });
    });
    const page = await context.newPage();
    let count = 0;
    for (const file of pages) {
      await page.goto('https://tg.test/' + encodeURIComponent(file));
      if (file === 'equip.html') await page.evaluate(() => document.querySelector('#areaLogin').style.display = 'block');
      if (file === 'redefinir-password.html') {
        // Render only the real form; auth requests and password submission stay disabled.
        const fn = fs.readFileSync(file, 'utf8').match(/    function mostrarFormulario\(\) \{[\s\S]*?\n    \}/)[0];
        await page.addScriptTag({ content: 'var cartao=document.getElementById("cartao");' + fn + ';mostrarFormulario();' });
      }
      count += await inspect(page, file);
    }
    await page.goto('https://tg.test/login.html');
    for (const [type, encoded] of Object.entries(templates.reports)) {
      await page.evaluate(html => {
        document.querySelector('#audit-frame')?.remove();
        const frame = document.createElement('iframe');
        frame.id = frame.name = 'audit-frame'; frame.style.width = '100%'; frame.srcdoc = html;
        document.body.append(frame);
      }, Buffer.from(encoded, 'base64').toString());
      await page.waitForFunction(() => document.querySelector('#audit-frame').contentDocument?.querySelector('#tg-form-focus-style')?.sheet);
      const frame = page.frame({ name: 'audit-frame' });
      // Templates start locked until the application supplies permission/context.
      // Enable their actual fields locally, including rows generated by report scripts.
      await frame.evaluate(selector => document.querySelectorAll(selector).forEach(el => { el.disabled = false; el.readOnly = false; }), controls);
      count += await inspect(frame, type);
    }
    assert(count > 1000, 'The audit must include dynamically generated report rows');
    console.log(`PASS: ${count} actual fields across ${pages.length} entry pages and ${Object.keys(templates.reports).length} report templates, at 100% and 80% container scale.`);
    await context.close();
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });

async function inspect(surface, label) {
  const result = await surface.evaluate(selector => {
    const fields = [...document.querySelectorAll(selector)].filter(el => !el.disabled && !el.readOnly);
    const failures = [];
    for (const scale of [1, .8]) {
      document.body.style.zoom = scale;
      for (const el of fields) {
        const before = el.value ?? el.textContent;
        el.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true, cancelable: true }));
        const font = parseFloat(getComputedStyle(el).fontSize);
        if (font * scale < 15.99) failures.push({ field: el.id || el.name || el.tagName, scale, font });
        if ((el.value ?? el.textContent) !== before) failures.push({ field: el.id, changedValue: true });
      }
    }
    return { count: fields.length, failures };
  }, controls);
  assert.deepEqual(result.failures, [], label);
  return result.count;
}
